/**
 * 將字串中的簡體字依對照表轉換為台灣繁體
 */
export function toTraditional(text: string): string {
  if (!text) return '';
  let result = '';
  for (let i = 0; i < text.length; i++) {
    const char = text[i];
    result += S2T_MAP[char] || char;
  }
  return result;
}
